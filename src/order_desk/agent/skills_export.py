"""Write the Hermes files from the one source of instructions.

The instructions live in order_desk/agent/instructions/*.md. Both runtimes
use them: the reference agent reads them directly, and this function copies
them into the two Hermes files for each sandbox:

    hermes/<role>-desk/SOUL.md                    always-on rules (Hermes loads SOUL.md every turn)
    hermes/<role>-desk/skills/<role>-desk/SKILL.md the same text as a skill, with frontmatter

Run `order-desk export-skills` after any change to the instructions.
"""

from __future__ import annotations

import json
from pathlib import Path

from order_desk.agent.loop import load_instructions

DESCRIPTIONS = {
    "dealer": "Take electrical orders from dealers: read chitti photos, confirm lines, and track orders "
              "with the Order Desk MCP tools.",
    "shop": "Help the shop owner and packers: approve orders, stock-in from invoices, payments and "
            "business questions with the Order Desk MCP tools.",
}

HEADER = "<!-- GENERATED by `order-desk export-skills` from src/order_desk/agent/instructions/{role}.md. Do not edit here. -->\n\n"


def export(out_dir: Path) -> list[Path]:
    written = []
    for role in ("dealer", "shop"):
        text = load_instructions(role)
        base = out_dir / f"{role}-desk"
        soul = base / "SOUL.md"
        skill = base / "skills" / f"{role}-desk" / "SKILL.md"
        skill.parent.mkdir(parents=True, exist_ok=True)
        soul.write_text(HEADER.format(role=role) + text, encoding="utf-8")
        frontmatter = (
            "---\n"
            f"name: {role}-desk\n"
            f"description: {json.dumps(DESCRIPTIONS[role])}\n"     # quoted: the text contains a colon
            "version: 0.1.0\n"
            "metadata:\n"
            "  hermes:\n"
            "    category: business\n"
            "    tags: [orders, telegram, mcp]\n"
            "---\n\n"
        )
        skill.write_text(frontmatter + HEADER.format(role=role) + text, encoding="utf-8")
        written += [soul, skill]
    return written
